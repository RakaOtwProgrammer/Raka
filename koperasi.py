# koperssi program operasi komperasi(perbandingan)
# operator : == , != , > ,< , >= , <=

a = 15
b = 10
print("==============================")
print("=========PERBANDINGAN=========")
print("==============================")
print("a = 15")
print("b = 10")
print("")
print("a == b :",a==b)
print("a != b :",a!=b)
print("a > b :",a>b)
print("a < b :",a<b)
print("a >= b :",a>=b)
print("a <= b :",a<=b)